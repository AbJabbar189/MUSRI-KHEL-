let currentLang = localStorage.getItem("misri_lang") || "ur";

function setLanguage(lang) {
    if (!i18n[lang]) lang = "ur";
    currentLang = lang;
    localStorage.setItem("misri_lang", lang);
    
    document.documentElement.lang = lang;
    document.documentElement.dir = i18n[lang].dir;
    
    // Switch body font class
    document.body.classList.remove("lang-ur", "lang-ps", "lang-en");
    document.body.classList.add(i18n[lang].fontClass);
    
    // Update all text nodes with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach(elem => {
        const key = elem.getAttribute("data-i18n");
        if (i18n[lang][key]) {
            elem.textContent = i18n[lang][key];
        }
    });
    
    // Update language buttons active state
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (btn.getAttribute("data-lang") === lang) {
            btn.classList.add("active");
        } else {
            btn.classList.remove("active");
        }
    });
}

document.addEventListener("DOMContentLoaded", () => {
    setLanguage(currentLang);
    
    document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.addEventListener("click", () => {
            const lang = btn.getAttribute("data-lang");
            setLanguage(lang);
        });
    });
});
